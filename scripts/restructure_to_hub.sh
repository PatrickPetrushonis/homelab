#!/usr/bin/env bash
# restructure_to_hub.sh: Reorganizes the video-encoder repo into a
# multi-domain "homelab" hub layout, using `git mv` throughout so file
# history is preserved rather than showing as delete+add.
#
# Usage:  ./restructure_to_hub.sh [-n]
#
# Options:
#   -n    Dry run: print the moves that would happen, do not run git mv
#   -h    Show this help
#
# Must be run from the repo root (where scripts/ and the *.md docs
# currently live) — a git repository, not a fresh checkout with
# uncommitted changes you care about losing (this script only moves
# tracked files; commit or stash first).
#
# Target layout:
#   ./
#   ├── README.md                        (new hub-level index — NOT
#   │                                      generated by this script, see
#   │                                      the note it prints at the end)
#   ├── SYSTEM_ARCHITECTURE.md
#   ├── system/
#   │   ├── system_inventory.sh
#   │   ├── NVIDIA_Driver_Fix_Summary.md
#   │   ├── kernel_panic_incident.md
#   │   └── GMMK_RGB_Lighting_Shortcuts.md
#   ├── video-encoder/
#   │   ├── README.md                    (current project README, kept)
#   │   └── scripts/
#   │       └── ... (all current scripts, unchanged relative to each other)
#   ├── llm/
#   │   └── Ollama_Docker_Debug_Reference.md
#   ├── nas/
#   │   ├── DS220__RAID_1_Upgrade__8TB_to_16TB.md
#   │   └── AUTOMATION_ROADMAP.md
#   └── web/
#       └── React_TS_Vite_GHPages_Setup_Guide.md

set -euo pipefail

DRY_RUN=0
while getopts ":nh" opt; do
    case $opt in
        n) DRY_RUN=1 ;;
        h) grep '^#' "$0" | grep -v '#!/' | sed 's/^# \{0,2\}//'; exit 0 ;;
        \?) echo "ERROR: Unknown option: -$OPTARG" >&2; exit 1 ;;
    esac
done

git rev-parse --is-inside-work-tree &>/dev/null || {
    echo "ERROR: not inside a git repository. Run from the repo root." >&2
    exit 1
}

if [[ -n "$(git status --porcelain)" ]] && (( ! DRY_RUN )); then
    echo "ERROR: uncommitted changes present. Commit or stash before restructuring," >&2
    echo "       so this is trivially revertible if anything looks wrong after." >&2
    exit 1
fi

# move OLD NEW — wraps git mv with dry-run support and existence checking,
# so a partially-applied prior run (or a file already moved by hand) doesn't
# abort the whole script.
move() {
    local old="$1" new="$2"
    if [[ ! -e "$old" ]]; then
        echo "SKIP (not found, already moved?): $old"
        return 0
    fi
    if [[ -e "$new" ]]; then
        echo "SKIP (destination already exists): $new"
        return 0
    fi
    echo "MOVE: $old -> $new"
    if (( ! DRY_RUN )); then
        mkdir -p "$(dirname "$new")"
        git mv "$old" "$new"
    fi
}

(( DRY_RUN )) && echo "=== DRY RUN: no files will be moved ==="

# --- system/ ---
move "NVIDIA_Driver_Fix_Summary.md"         "system/NVIDIA_Driver_Fix_Summary.md"
move "Kernel_Panic_Incident.md"             "system/Kernel_Panic_Incident.md"
move "GMMK_RGB_Lighting_Shortcuts.md"       "system/GMMK_RGB_Lighting_Shortcuts.md"
move "scripts/system_inventory.sh"          "system/system_inventory.sh"

# --- video-encoder/ (keep internal structure, just nest under the domain dir) ---
move "scripts/config.sh"            "video-encoder/scripts/config.sh"
move "scripts/encoder.sh"           "video-encoder/scripts/encoder.sh"
move "scripts/encoder_dry.sh"       "video-encoder/scripts/encoder_dry.sh"
move "scripts/encoder_params.sh"    "video-encoder/scripts/encoder_params.sh"
move "scripts/rename.sh"            "video-encoder/scripts/rename.sh"
move "scripts/rename_dry.sh"        "video-encoder/scripts/rename_dry.sh"
move "scripts/rename_params.sh"       "video-encoder/scripts/rename_params.sh"
move "scripts/lang_table.sh"        "video-encoder/scripts/lang_table.sh"
move "scripts/lang_table.tsv"       "video-encoder/scripts/lang_table.tsv"
move "README.md"                    "video-encoder/README.md"

# --- llm/ ---
move "Ollama_Docker_Debug_Reference.md"  "llm/Ollama_Docker_Debug_Reference.md"

# --- nas/ ---
move "NAS_DS220_Upgrade_Guide.md"   "nas/NAS_DS220_Upgrade_Guide.md"
move "Automation_Roadmap.md"        "nas/Automation_Roadmap.md"

# --- web/ ---
move "React_TS_Vite_GHPages_Setup_Guide.md"   "web/React_TS_Vite_GHPages_Setup_Guide.md"

# --- stays at repo root ---
# SYSTEM_ARCHITECTURE.md is intentionally left in place: it's the hub-level
# spine, not a single-domain doc.

echo ""
if (( DRY_RUN )); then
    echo "Dry run complete. Re-run without -n to apply."
else
    echo "Restructure complete."
    echo ""
    echo "NOT done automatically, do these next:"
    echo "  1. Write a new root README.md (hub index) — the old video-encoder"
    echo "     README now lives at video-encoder/README.md and stays exactly"
    echo "     as the project-level doc for that domain; the new root one"
    echo "     should be a short index pointing into system/, video-encoder/,"
    echo "     llm/, nas/, web/, and SYSTEM_ARCHITECTURE.md."
    echo "  2. Update any path references inside the moved docs themselves"
    echo "     (e.g. SYSTEM_ARCHITECTURE.md points at 'DS220__RAID...' by"
    echo "     bare filename in a few places — those still resolve via"
    echo "     relative doc-to-doc references, but double check)."
    echo "  3. Review with 'git status' and 'git diff --stat' before committing."
fi